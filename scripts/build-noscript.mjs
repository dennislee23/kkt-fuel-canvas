#!/usr/bin/env node
/* build-noscript.mjs — inject a JS-free catalog fallback into index.html.
 *
 * The canvas renders client-side (React + in-browser Babel), so AI fetchers
 * that don't run JavaScript (GPTBot, ClaudeBot, PerplexityBot, OAI-SearchBot)
 * see only the <head> — ~6 words of body. This inlines the FULL catalog as
 * semantic HTML inside a <noscript> block, from the SAME data the canvas
 * renders (existing/roadmap-data.js, the *_EN structures). Human visitors run
 * JS, so <noscript> never renders for them — zero visual change, no flash.
 *
 * Idempotent: replaces the content between the SEO-FALLBACK markers on each run.
 *
 * ⚠️ Re-run after a new canvas export replaces existing/roadmap-data.js:
 *      node scripts/build-noscript.mjs   (alongside build-llms.mjs / build-catalog.mjs)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

const dataSrc = readFileSync(join(root, 'existing/roadmap-data.js'), 'utf8');
const win = {};
new Function('window', dataSrc)(win);

const BLOCKS   = win.FUEL_BLOCKS_EN   || win.FUEL_BLOCKS   || [];
const PROBLEMS = win.FUEL_PROBLEMS_EN || win.FUEL_PROBLEMS || [];
const CARDS    = win.FUEL_CARDS_EN    || win.FUEL_CARDS    || [];
const STAGES   = win.FUEL_STAGES_EN   || win.FUEL_STAGES   || [];

const stageName = (id) => (STAGES.find((s) => s.id === id) || {}).name || `Stage ${id}`;
const bySeq = (a, b) => (a.sequence || 0) - (b.sequence || 0);
const esc = (s) => String(s ?? '')
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const h = [];
h.push('<h1>Fuel AI Transformation Map — KKT</h1>');
h.push('<p>An interactive map of where data and AI deliver measurable results across a fuel-retail network, published by Kitty Kat Technologies (KKT), a data, AI and automation delivery firm in Tallinn, Estonia (EU). It spans the whole network economy — procurement and margin, logistics, stations and shops, customers, finance and control — built bottom-up: connected data and control first, then AI where it earns its place. KKT’s marquee fuel deployment is Optimus, a procurement-and-margin engine in pilot at Red Petroleum, a 250-station independent fuel network in Kyrgyzstan.</p>');

h.push('<h2>Maturity stages</h2><ul>');
for (const s of STAGES) h.push(`<li><strong>${esc(s.name)}</strong> — ${esc(s.description)}</li>`);
h.push('</ul>');

h.push(`<h2>The map — ${BLOCKS.length} domains, ${PROBLEMS.length} challenges, ${CARDS.length} solutions</h2>`);
for (const block of [...BLOCKS].sort(bySeq)) {
  h.push(`<h3>${esc(block.code)} — ${esc(block.title)}</h3>`);
  if (block.spine) h.push(`<p>${esc(block.spine)}</p>`);
  const problems = PROBLEMS.filter((p) => p.blockId === block.id).sort(bySeq);
  for (const p of problems) {
    h.push(`<h4>${esc(p.code)} · ${esc(p.title)}${p.painLine ? ' — ' + esc(p.painLine) : ''}</h4><ul>`);
    for (const c of CARDS.filter((c) => c.problemId === p.id).sort(bySeq)) {
      const lock = c.lock ? ' [prerequisite]' : '';
      const desc = c.shortDescription ? ' — ' + esc(c.shortDescription) : '';
      h.push(`<li>${esc(c.title)} <em>(${esc(stageName(c.stage))})</em>${lock}${desc}</li>`);
    }
    h.push('</ul>');
  }
}
h.push('<p><a href="https://kittykat.tech/">Kitty Kat Technologies</a> · <a href="https://kittykat.tech/solutions/optimus/">Optimus</a> · <a href="https://kittykat.tech/industries/fuel-retail/">Fuel retail</a> · <a href="/llms.txt">Text version (llms.txt)</a></p>');

const BLOCK =
  '<!-- SEO-FALLBACK:START (generated by scripts/build-noscript.mjs — do not edit by hand) -->\n' +
  '<noscript>\n<div class="seo-fallback">\n' + h.join('\n') + '\n</div>\n</noscript>\n' +
  '<!-- SEO-FALLBACK:END -->';

const START = '<!-- SEO-FALLBACK:START';
const END = '<!-- SEO-FALLBACK:END -->';
let html = readFileSync(join(root, 'index.html'), 'utf8');

if (html.includes(START)) {
  html = html.replace(new RegExp(START + '[\\s\\S]*?' + END.replace(/[-]/g, '\\$&')), BLOCK);
} else {
  // Insert right after the React mount point.
  html = html.replace(/(<div id="root">\s*<\/div>)/, `$1\n${BLOCK}`);
}
writeFileSync(join(root, 'index.html'), html);
console.error(`noscript fallback injected: ${BLOCKS.length} domains, ${PROBLEMS.length} challenges, ${CARDS.length} solutions`);
